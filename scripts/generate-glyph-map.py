#!/usr/bin/env python3
import hashlib
import json
import pathlib
import sys

# Semantic name -> full upstream metadata key. The metadata file is a flat
# dictionary: {"ic_fluent_music_note_2_24_regular": 61697, ...}.
MAP = {
    "Music": "ic_fluent_music_note_2_24_regular",
    "Camera": "ic_fluent_camera_24_regular",
    "Shelf": "ic_fluent_library_24_regular",
    "Focus": "ic_fluent_timer_24_regular",
    "Settings": "ic_fluent_settings_24_regular",
    "ChevronUp": "ic_fluent_chevron_up_24_regular",
    "Previous": "ic_fluent_previous_24_regular",
    "Next": "ic_fluent_next_24_regular",
    "Play": "ic_fluent_play_24_regular",
    "Pause": "ic_fluent_pause_24_regular",
    "Lyrics": "ic_fluent_chat_24_regular",
    "Wifi": "ic_fluent_wifi_1_24_regular",
    "Volume": "ic_fluent_speaker_2_24_regular",
    "Mute": "ic_fluent_speaker_mute_24_regular",
    "Brightness": "ic_fluent_brightness_high_24_regular",
    "Charging": "ic_fluent_battery_charge_24_regular",
    "Refresh": "ic_fluent_arrow_clockwise_24_regular",
    "Info": "ic_fluent_info_24_regular",
    "Appearance": "ic_fluent_paint_brush_24_regular",
    "Close": "ic_fluent_dismiss_24_regular",
}

def find_codepoint(metadata, key):
    value = metadata.get(key)
    if not isinstance(value, int):
        raise SystemExit(f"icon not found in metadata: {key}")
    return value

def main():
    if len(sys.argv) not in (3, 4):
        raise SystemExit(
            "usage: generate-glyph-map.py <metadata.json> <output.g.cs> [font.ttf]"
        )
    metadata = json.loads(pathlib.Path(sys.argv[1]).read_text())
    font_sha = None
    if len(sys.argv) == 4:
        font_sha = hashlib.sha256(pathlib.Path(sys.argv[3]).read_bytes()).hexdigest()
    lines = ["// <auto-generated />", "namespace Aster.UI.Controls;", "",
             "public static partial class GlyphMap", "{"]
    if font_sha is not None:
        lines += [f'    public const string FontSha256 = "{font_sha}";', ""]
    lines += ["    public static readonly",
              "        System.Collections.Generic.IReadOnlyDictionary<Glyph.Kind, int> Codepoints =",
              "        new System.Collections.Generic.Dictionary<Glyph.Kind, int>", "        {"]
    for semantic, key in MAP.items():
        codepoint = find_codepoint(metadata, key)
        lines.append(f"            [Glyph.Kind.{semantic}] = 0x{codepoint:X},")
    lines += ["        };", "}"]
    pathlib.Path(sys.argv[2]).write_text("\n".join(lines) + "\n")

if __name__ == "__main__":
    main()
